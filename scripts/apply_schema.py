#!/usr/bin/env python3
"""
STEP 2: Apply master_schema.csv to raw CSVs → outputs/unified_registry.csv

Reads master_schema.csv (generated by two_stage_match.py) and applies it
to one or more raw datasets, producing a single PII-free, harmonised registry
with full terminology normalization and per-field provenance tracking.

Scientific properties
---------------------
1. **Variable-level rules** — every harmonized column is governed by an
   explicit VariableRule (unit, allowable range/values, phenotype definition,
   timing window, transform function) imported from variable_rules.py.
2. **Terminology normalization** — raw heterogeneous values are normalized
   through typed transforms (normalize_boolean, normalize_gender, etc.)
   enforced at transform time, not just structural column selection.
3. **Per-field provenance** — each (row, column) cell in the output is tracked
   in a provenance log: source column(s), source value, transform applied,
   harmonized value, validation status, confidence, and reviewer flag.
   Saved to outputs/provenance.csv alongside the main registry.
4. **Harmonization tiers** — every column is tagged as one of:
     schema_aligned           — column names matched; raw values pass through
     semantically_harmonized  — terminology normalized; values validated
     analysis_ready           — unit-standardized, range-validated, phenotype-defined
   Tier assignments come from variable_rules.py and are exported in
   outputs/harmonization_tiers.csv.
5. **Cohort comparability hooks** — the unified registry includes a ``cohort``
   column so downstream scripts (cohort_comparability.py) can run distribution,
   missingness, and protocol-difference analyses before pooling.

Usage
-----
  python scripts/apply_schema.py \\
      outputs/master_schema.csv \\
      db/BHS_Full.csv db/EHVol_Full.csv \\
      --output outputs/unified_registry.csv
"""
